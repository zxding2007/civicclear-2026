"""The static site's data bundle: built from the same checks as the pipeline; never calls a model."""
import json
from pathlib import Path

import build_site

ROOT = Path(__file__).resolve().parents[1]


def test_bundle_statuses_match_golden_answers():
    data = build_site.build()
    assert [i['id'] for i in data['items']][:4] == build_site.DEMO_ORDER
    for item in data['items']:
        golden = json.loads((ROOT / 'data' / 'items' / item['id'] / 'golden.json').read_text(encoding='utf-8'))
        assert item['status'] == golden['expected_status']
        assert all(item['checks']['stages'])


def test_bundle_tax_example_matches_calculator():
    tax = build_site.build()['tax']
    assert tax['example'] == {'assessed_value': 700000, 'before': 4207.61, 'after': 4300.18, 'difference': 92.57}


def test_bundle_links_are_official_https():
    for item in build_site.build()['items']:
        assert item['meta']['item_url'].startswith('https://secure.toronto.ca/')
        for seg in item['explanation']:
            for src in seg['sources']:
                assert src['url'].startswith('https://')


def test_written_bundle_is_plain_javascript(tmp_path, monkeypatch):
    out = tmp_path / 'data.js'
    monkeypatch.setattr(build_site, 'OUT', out)
    build_site.main()
    text = out.read_text(encoding='utf-8')
    assert text.startswith('// Generated by build_site.py')
    body = text[text.index('{'):text.rstrip().rindex(';')]
    assert json.loads(body)['items']
