"""Bundle the decision records into site/data.js for the static website.

    python build_site.py

The website never calls an AI model. This script runs the same checks the API
pipeline runs on a new card, so the page shows only what passed them:

- every quote is looked up in the saved official text (pipeline.verify);
- the decision status is computed by rules (pipeline.status), never copied from a model;
- the computed status must equal the stored status and the human golden answer,
  otherwise the build stops.

The result is a plain JavaScript file, so the page also works when opened
straight from disk, with no server.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from calculator import compare
from pipeline.evidence import read_evidence
from pipeline.schema import DecisionCard
from pipeline.status import overall_status
from pipeline.verify import verify_card, verify_explanation_segments

ROOT = Path(__file__).resolve().parent
ITEMS = ROOT / 'data' / 'items'
OUT = ROOT / 'site' / 'data.js'

# The order residents see: the clearest "received is not approved" case first.
DEMO_ORDER = ['2026.DM41.4', '2026.PH29.2', '2026.PH29.1', '2026.CC38.1']

HAVE_YOUR_SAY = 'https://www.toronto.ca/city-government/council/council-committee-meetings/have-your-say/'


def _read(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def build_item(folder: Path) -> dict:
    meta = _read(folder / 'meta.json')
    stored = _read(folder / 'card.json')
    card = DecisionCard.model_validate(stored['card'])
    page_text = (folder / 'item_page.txt').read_text(encoding='utf-8')

    checks = verify_card(card, page_text)
    status = overall_status(card, checks['stages'])
    if status != stored.get('status'):
        raise ValueError(f'{folder.name}: computed status {status!r} differs from stored {stored.get("status")!r}')
    golden_path = folder / 'golden.json'
    if golden_path.exists():
        expected = _read(golden_path).get('expected_status')
        if expected and expected != status:
            raise ValueError(f'{folder.name}: status {status!r} differs from golden answer {expected!r}')

    explanation = verify_explanation_segments(_read(folder / 'explanation.json'), page_text)
    evidence = read_evidence(ROOT / 'data' / 'evidence_impact.json', card.item_id)

    return {
        'id': card.item_id,
        'short_title': meta.get('short_title') or card.title,
        'meta': meta,
        'card': card.model_dump(),
        'checks': checks,
        'status': status,
        'explanation': explanation,
        'evidence': evidence,
    }


def build() -> dict:
    folders = [p for p in ITEMS.iterdir() if p.is_dir() and (p / 'card.json').exists()]
    folders.sort(key=lambda p: (DEMO_ORDER.index(p.name) if p.name in DEMO_ORDER else len(DEMO_ORDER), p.name))
    rates = _read(ROOT / 'data' / 'tax_rates.json')
    residential = rates['residential']
    return {
        'built_on': date.today().isoformat(),
        'have_your_say_url': HAVE_YOUR_SAY,
        'items': [build_item(p) for p in folders],
        'glossary': _read(ROOT / 'data' / 'glossary.json'),
        'wards': _read(ROOT / 'data' / 'wards.json'),
        'tax': {
            'residential': residential,
            'assumption': rates.get('assumption', ''),
            # Worked example from calculator.py; the page checks its own maths against it.
            'example': {'assessed_value': 700000,
                        **compare(700000, residential['2025']['rate_percent'], residential['2026']['rate_percent'])},
        },
    }


def main() -> None:
    data = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, ensure_ascii=False, indent=1)
    OUT.write_text('// Generated by build_site.py. Do not edit by hand.\nwindow.CIVICCLEAR = ' + body + ';\n', encoding='utf-8')
    print(f'Wrote {OUT}: {len(data["items"])} decisions, statuses ' +
          ', '.join(f'{i["id"]}={i["status"]}' for i in data['items']))


if __name__ == '__main__':
    main()
